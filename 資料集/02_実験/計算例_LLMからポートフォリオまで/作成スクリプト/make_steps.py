def n(x, d):
    """A fixed-point number; '-' for negatives, no '-0'."""
    s = f'{x:,.{d}f}'
    s = s[1:] if s.startswith('-') and float(s.replace(',', '')) == 0 else s
    return s.replace(',', '{,}')          # a thousands comma in math mode without the space after it


def p(x, d):
    """The same, in parentheses when negative (as a factor in a product)."""
    s = n(x, d)
    return f'({s})' if s.startswith('-') else s


def sym(i):
    return r'\textsf{' + SYM[i] + '}'


def write(name, lines):
    OUT.mkdir(exist_ok=True)
    (OUT / f'{name}.tex').write_text('% generated by 作成スクリプト/make_steps.py; do not edit\n' + '\n'.join(lines) + '\n',
                                     encoding='utf-8')


def check(a, b, tol, what):
    if abs(a - b) > tol:
        raise SystemExit(f'{what}: {a} != {b}')


# ---- 2. the ridge score: standardize, multiply, add -------------------------------------------------------------
L = []
for i, s in enumerate(ST):
    L.append(r'\begin{calc}[' + sym(i) + r'：標準化と掛け算（$j=1$〜$4$）]')
    L.append(r'\begin{align*}')
    for j in range(4):
        x, m, sd, b = s['x_first'][j], R['mu_first'][j], R['sd_first'][j], R['beta_first'][j]
        xs = (x - m) / sd
        check(xs, s['xs_first'][j], 1e-4, 'xs')
        c = xs * b
        L.append(rf'\tilde x_{j + 1} &= \frac{{{n(x, 4)} - {p(m, 4)}}}{{{n(sd, 4)}}} = \frac{{{n(x - m, 4)}}}{{{n(sd, 4)}}} = {n(xs, 4)},\quad '
                 rf'\tilde x_{j + 1}\hat\beta_{j + 1} = {p(xs, 4)}\times{p(b, 6)} = {n(c, 6)}\\')
    L.append(r'\end{align*}')
    c4 = sum(s['contrib_first'])
    L.append(r'足し算：')
    L.append(r'\begin{align*}')
    terms = ' + '.join(p(c, 6) for c in s['contrib_first'])
    L.append(rf'\text{{最初の 4 項}} &= {terms} = {n(c4, 6)}\\')
    L.append(rf'\hat y &= \hat b + (\text{{最初の 4 項}}) + (\text{{残り 1,532 項}})\\ &= {p(R["b0"], 7)} + {p(c4, 6)} + {p(s["contrib_rest"], 6)} = \mathbf{{{n(s["pred"], 4)}}}\\')
    ret = s['pred'] * R['y_sd'] + R['y_mean']
    L.append(rf'\text{{2 日の反応に直す}} &= {p(s["pred"], 4)}\times{n(100 * R["y_sd"], 3)}\% + {n(100 * R["y_mean"], 3)}\%\\ '
             rf'&= {n(100 * s["pred"] * R["y_sd"], 3)}\% + {n(100 * R["y_mean"], 3)}\% = {n(100 * ret, 2)}\%')
    L.append(r'\end{align*}')
    L.append(r'\end{calc}')
write('ridge', L)

# ---- 3. Blom ------------------------------------------------------------------------------------------------------
L = [r'\begin{calc}[順位から $z$ へ（$N=' + str(ST[0]['N']) + r'$）]', r'\begin{align*}']
for i, s in enumerate(ST):
    num, den = s['rank'] - 0.375, s['N'] + 0.25
    qt = num / den
    z = stats.norm.ppf(qt)
    check(z, s['z'], 1e-9, 'z')
    L.append(rf'{sym(i)}:\quad \frac{{{n(s["rank"], 0)} - 0.375}}{{{s["N"]} + 0.25}} &= \frac{{{n(num, 3)}}}{{{n(den, 2)}}} = {n(qt, 4)}, &'
             rf'z &= \Phi^{{-1}}({n(qt, 4)}) = \mathbf{{{n(z, 3)}}}\\')
L += [r'\end{align*}',
      r'$\Phi^{-1}(0.9331)=1.499$ は「標準正規分布で、下から 93.31\% の位置の値」。'
      r'$\Phi^{-1}(0.5)=0$（真ん中）、$\Phi^{-1}(0.0669)=-1.499$（上と左右対称）。',
      r'\end{calc}']
write('blom', L)

# ---- 4. sigma and covariance ---------------------------------------------------------------------------------------
S = np.array(v['cov']['S3_daily'])
r252 = np.sqrt(252)
L = [r'\begin{calc}[変動率：$\sigma_i = s_i\times\sigma_{0,i}$、年率は $\times\sqrt{252}=' + n(r252, 4) + r'$]', r'\begin{align*}']
for i, s in enumerate(ST):
    L.append(rf'{sym(i)}:\quad \sigma_{i + 1} &= {n(s["s"], 4)}\times{n(100 * s["sigma0"], 4)}\% = {n(100 * s["sigma"], 4)}\%, &'
             rf'\text{{年率}} &= {n(100 * s["sigma"], 4)}\%\times{n(r252, 4)} = {n(100 * s["sigma"] * r252, 1)}\%\\')
L += [r'\end{align*}', r'\end{calc}']
L += [r'\begin{calc}[共分散 $\Sigma$（日次）と、年率・相関への直し方]',
      r'\[ \Sigma = \begin{pmatrix}' + r'\\'.join(' & '.join(n(S[a, b], 7) for b in range(3)) for a in range(3)) + r'\end{pmatrix}\]',
      r'\begin{align*}',
      rf'\text{{年率}}:\ 252\,\Sigma_{{11}} &= 252\times{n(S[0, 0], 7)} = {n(252 * S[0, 0], 4)}\\'
      rf'\sqrt{{{n(252 * S[0, 0], 4)}}} &={n(np.sqrt(252 * S[0, 0]), 4)} = {n(100 * np.sqrt(252 * S[0, 0]), 1)}\%\ (\text{{\Sym{{1}} の年率の変動率}})\\',
      rf'\text{{相関}}:\ \rho_{{12}} &= \frac{{\Sigma_{{12}}}}{{\sqrt{{\Sigma_{{11}}}}\sqrt{{\Sigma_{{22}}}}}}\\ &= '
      rf'\frac{{{n(S[0, 1], 7)}}}{{{n(np.sqrt(S[0, 0]), 5)}\times{n(np.sqrt(S[1, 1]), 5)}}} = '
      rf'\frac{{{n(S[0, 1], 7)}}}{{{n(np.sqrt(S[0, 0] * S[1, 1]), 7)}}} = {n(S[0, 1] / np.sqrt(S[0, 0] * S[1, 1]), 3)}',
      r'\end{align*}',
      r'$\Sigma_{ii}$ は $\sigma_i^2$ とわずかに違う（$\Sigma$ は Ledoit--Wolf で縮めた後、$\sigma_i$ は縮める前の標準偏差）。',
      r'\end{calc}']
write('cov', L)

